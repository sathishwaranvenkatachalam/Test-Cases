import fs from 'node:fs';
import path from 'node:path';
import { db } from './db.js';
import { sha1, stableStringify, normalizeKey, slugify } from './util.js';

const GEN_DIR = path.resolve('playwright', 'generated');

export function paramsHash(params: Record<string, string>): string {
  return sha1(stableStringify(params));
}

export function expectedHash(expected: string): string {
  return sha1(normalizeKey(expected));
}

export function saveRecording(
  stepId: number,
  kind: 'action' | 'assert',
  code: string,
  params?: Record<string, string>,
  expected?: string,
): void {
  if (!code || code.trim() === '') return;
  const ph = kind === 'action' ? '' : paramsHash(params ?? {});
  const eh = kind === 'action' ? '' : expectedHash(expected ?? '');
  db.prepare(
    `INSERT INTO recordings (step_id, kind, params_hash, expected_hash, code)
     VALUES (?, ?, ?, ?, ?)
     ON CONFLICT(step_id, kind, params_hash, expected_hash)
     DO UPDATE SET code = excluded.code, verified_at = datetime('now')`,
  ).run(stepId, kind, ph, eh, code);
}

export function caseIsFullyRecorded(caseId: number): { ok: boolean; missing: string[] } {
  const rows = db.prepare(
    'SELECT step_id AS stepId, params_json AS params, expected FROM case_steps WHERE case_id = ? ORDER BY position',
  ).all(caseId) as { stepId: number; params: string; expected: string | null }[];

  const findAction = db.prepare(
    "SELECT 1 FROM recordings WHERE step_id = ? AND kind = 'action' AND params_hash = '' AND expected_hash = ''",
  );
  const findAssert = db.prepare(
    "SELECT 1 FROM recordings WHERE step_id = ? AND kind = 'assert' AND params_hash = ? AND expected_hash = ?",
  );

  const missing: string[] = [];
  for (const r of rows) {
    if (!findAction.get(r.stepId)) missing.push(`step ${r.stepId} action`);
    if (r.expected && r.expected.trim() !== '') {
      const params = JSON.parse(r.params) as Record<string, string>;
      if (!findAssert.get(r.stepId, paramsHash(params), expectedHash(r.expected))) {
        missing.push(`step ${r.stepId} assert`);
      }
    }
  }
  return { ok: missing.length === 0, missing };
}

export function flowCoverage(flowId: number): { total: number; covered: number; status: 'none' | 'partial' | 'complete' } {
  const caseIds = (db.prepare('SELECT id FROM cases WHERE flow_id = ? ORDER BY id').all(flowId) as { id: number }[])
    .map(r => r.id);
  const total = caseIds.length;
  const covered = caseIds.filter(id => caseIsFullyRecorded(id).ok).length;
  const status: 'none' | 'partial' | 'complete' =
    covered === 0 ? 'none' : covered === total && total > 0 ? 'complete' : 'partial';
  return { total, covered, status };
}

function commentSafe(s: string): string {
  return s.replace(/\r?\n/g, ' ').replace(/\*\//g, '* /');
}

function indentCode(code: string, spaces: number): string[] {
  const pad = ' '.repeat(spaces);
  return code.split(/\r?\n/).map(l => (l.length > 0 ? pad + l : ''));
}

export function regenerateStepsFile(): string {
  fs.mkdirSync(GEN_DIR, { recursive: true });
  const rows = db.prepare(
    `SELECT s.id AS id, s.canonical_text AS text, r.code AS code
       FROM steps s JOIN recordings r ON r.step_id = s.id AND r.kind = 'action'
      ORDER BY s.id`,
  ).all() as { id: number; text: string; code: string }[];

  const lines: string[] = [
    '// AUTO-GENERATED by Test Flow Manager. Do not edit.',
    "import { expect, type Page } from '@playwright/test';",
    'export type P = Record<string, string>;',
    '',
  ];
  for (const r of rows) {
    lines.push(`// ${commentSafe(r.text)}`);
    lines.push(`export async function step_${r.id}(page: Page, p: P): Promise<void> {`);
    lines.push('  void expect; void p;');
    lines.push(...indentCode(r.code, 2));
    lines.push('}');
    lines.push('');
  }
  const file = path.join(GEN_DIR, 'steps.ts');
  fs.writeFileSync(file, lines.join('\n'), 'utf8');
  return file;
}

export function regenerateFlowScripts(flowId: number): {
  specPath: string; coveredCases: number; totalCases: number; skipped: { caseId: number; missing: string[] }[];
} {
  regenerateStepsFile();

  const flow = db.prepare('SELECT id, name FROM flows WHERE id = ?').get(flowId) as { id: number; name: string } | undefined;
  if (!flow) throw new Error('flow not found');
  const specPath = path.join(GEN_DIR, `${slugify(flow.name)}.spec.ts`);

  const cases = db.prepare('SELECT id, title FROM cases WHERE flow_id = ? ORDER BY id').all(flowId) as { id: number; title: string }[];
  const skipped: { caseId: number; missing: string[] }[] = [];
  const covered: { id: number; title: string }[] = [];
  for (const c of cases) {
    const rec = caseIsFullyRecorded(c.id);
    if (rec.ok) covered.push(c);
    else skipped.push({ caseId: c.id, missing: rec.missing });
  }

  if (covered.length === 0) {
    if (fs.existsSync(specPath)) fs.rmSync(specPath, { force: true });
    return { specPath, coveredCases: 0, totalCases: cases.length, skipped };
  }

  const findAssert = db.prepare(
    "SELECT code FROM recordings WHERE step_id = ? AND kind = 'assert' AND params_hash = ? AND expected_hash = ?",
  );
  const caseSteps = db.prepare(
    'SELECT step_id AS stepId, params_json AS params, expected FROM case_steps WHERE case_id = ? ORDER BY position',
  );

  const out: string[] = [
    '// AUTO-GENERATED by Test Flow Manager. Do not edit.',
    "import { test, expect } from '../support';",
    "import * as S from './steps';",
    '',
    `test.describe(${JSON.stringify(flow.name)}, () => {`,
  ];
  for (const s of skipped) {
    out.push(`  // C${s.caseId} skipped (missing recordings): ${s.missing.join(', ')}`);
  }
  for (const c of covered) {
    out.push(`  test(${JSON.stringify(`C${c.id} ${c.title}`)}, async ({ page }) => {`);
    const steps = caseSteps.all(c.id) as { stepId: number; params: string; expected: string | null }[];
    for (const st of steps) {
      const params = JSON.parse(st.params) as Record<string, string>;
      out.push(`    await S.step_${st.stepId}(page, ${JSON.stringify(params)});`);
      if (st.expected && st.expected.trim() !== '') {
        out.push(`    // expected: ${commentSafe(st.expected)}`);
        const a = findAssert.get(st.stepId, paramsHash(params), expectedHash(st.expected)) as { code: string } | undefined;
        if (a) {
          const usesP = /\bp\[/.test(a.code) || /\bp\./.test(a.code);
          if (usesP) {
            out.push(`    {`);
            out.push(`      const p: Record<string, string> = ${JSON.stringify(params)};`);
            out.push(...indentCode(a.code, 6));
            out.push(`    }`);
          } else {
            out.push(...indentCode(a.code, 4));
          }
        }
      }
    }
    out.push('  });');
  }
  out.push('});');
  out.push('');

  fs.writeFileSync(specPath, out.join('\n'), 'utf8');
  return { specPath, coveredCases: covered.length, totalCases: cases.length, skipped };
}
